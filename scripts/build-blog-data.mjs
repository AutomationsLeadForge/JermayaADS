import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const RESEARCH = path.join(ROOT, "docs/research/blog");
const MANIFEST = path.join(RESEARCH, "manifest.json");
const POSTS_DIR = path.join(RESEARCH, "posts");
const MAP_PATH = path.join(RESEARCH, "image-map.json");
const OUT_TS = path.join(ROOT, "src/lib/blog.ts");
const OUT_BODIES = path.join(ROOT, "public/blog");

/** Rewrite <img src> / <a href> to local paths where the URL is in our map. */
function rewriteHtml(html, imageMap) {
  if (!html) return "";
  let out = html;

  // Rewrite <img src="...">
  out = out.replace(
    /<img([^>]*?)src=(["'])([^"']+)\2([^>]*?)>/g,
    (_, pre, q, src, post) => {
      const local = imageMap[src];
      return `<img${pre}src=${q}${local ?? src}${q}${post}>`;
    },
  );

  // Strip tracking/share anchor classes, add target=_blank to external <a>
  out = out.replace(
    /<a([^>]*?)href=(["'])([^"']+)\2([^>]*)>/g,
    (m, pre, q, href, post) => {
      if (!/target=/.test(m) && /^https?:\/\//.test(href)) {
        return `<a${pre}href=${q}${href}${q} target="_blank" rel="noopener noreferrer"${post}>`;
      }
      return m;
    },
  );

  return out.trim();
}

async function main() {
  const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
  const imageMap = JSON.parse(await readFile(MAP_PATH, "utf8"));

  const files = await readdir(POSTS_DIR);
  const postsBySlug = {};
  for (const f of files) {
    if (!f.endsWith(".json")) continue;
    const data = JSON.parse(await readFile(path.join(POSTS_DIR, f), "utf8"));
    postsBySlug[data.slug] = data;
  }

  await mkdir(OUT_BODIES, { recursive: true });

  // Use manifest order (newest-first)
  const summaries = [];
  for (const m of manifest.posts) {
    const p = postsBySlug[m.slug];
    if (!p) continue;
    const heroImage = p.heroImage ? imageMap[p.heroImage] ?? p.heroImage : null;
    const bodyHtml = rewriteHtml(p.bodyHtml, imageMap);

    // Per-post body file — fetched on demand by BlogContent
    await writeFile(
      path.join(OUT_BODIES, `${p.slug}.json`),
      JSON.stringify({ slug: p.slug, bodyHtml }),
      "utf8",
    );

    summaries.push({
      slug: p.slug,
      title: p.title,
      date: p.date,
      excerpt: p.excerpt ?? "",
      heroImage,
      url: p.url,
    });
  }

  const body = `// Auto-generated by scripts/build-blog-data.mjs — re-run after updating
// docs/research/blog/posts/*.json or rerunning the asset download script.
// Summary-only data — bodyHtml is fetched per-post from /blog/<slug>.json.
// Source: https://jermayads.nl/blog

export interface BlogPost {
  slug: string;
  title: string;
  /** ISO YYYY-MM-DD */
  date: string;
  excerpt: string;
  /** Local path under public/, or null if no hero. */
  heroImage: string | null;
  /** Original post URL on jermayads.nl — kept for reference only. */
  url: string;
}

export const BLOG_POSTS: BlogPost[] = ${JSON.stringify(summaries, null, 2)};
`;

  await writeFile(OUT_TS, body, "utf8");
  console.log(`Wrote ${OUT_TS} — ${summaries.length} summaries`);
  console.log(`Wrote ${summaries.length} body files → ${OUT_BODIES}/`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
